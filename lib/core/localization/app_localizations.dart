  /// Reverse lookup map for English phrase -> Key
  static final Map<String, String> _englishPhraseToKey = () {
    final map = <String, String>{};
    final enMap = _localizedValues['en']!;
    for (final entry in enMap.entries) {
      map[entry.value.trim().toLowerCase()] = entry.key;
    }
    return map;
  }();

  /// Primary translation method:
  /// Accepts either a key (e.g. 'home') or raw English text (e.g. 'Home' or 'Care Within Reach • Menstrual Health & Dignity')
  String translate(String keyOrText) {
    final langCode = locale.languageCode.toLowerCase();
    final cleanInput = keyOrText.trim();
    if (cleanInput.isEmpty) return keyOrText;

    final targetDict = _localizedValues[langCode] ?? _localizedValues['en']!;

    // 1. Direct key lookup
    if (targetDict.containsKey(cleanInput)) {
      return targetDict[cleanInput]!;
    }

    // 2. Lookup via lowercased key
    final lowerKey = cleanInput.toLowerCase();
    for (final k in targetDict.keys) {
      if (k.toLowerCase() == lowerKey) {
        return targetDict[k]!;
      }
    }

    // 3. Lookup by English text mapping
    final mappedKey = _englishPhraseToKey[lowerKey];
    if (mappedKey != null && targetDict.containsKey(mappedKey)) {
      return targetDict[mappedKey]!;
    }

    // 4. Substring / phrase matching for partial English sentences
    for (final entry in _englishPhraseToKey.entries) {
      if (lowerKey.contains(entry.key) && entry.key.length > 5) {
        final key = entry.value;
        if (targetDict.containsKey(key)) {
          return targetDict[key]!;
        }
      }
    }

    // 5. Fallback to English dictionary
    final enDict = _localizedValues['en']!;
    if (mappedKey != null && enDict.containsKey(mappedKey)) {
      return enDict[mappedKey]!;
    }

    return keyOrText;
  }
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<AppLocalizations> load(Locale locale) {
    return Future.value(AppLocalizations(locale));
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => true;
}

extension LocalizationContextExtension on BuildContext {
  String tr(String keyOrText) => AppLocalizations.of(this).translate(keyOrText);
}

extension AppLocalizationsStringExtension on String {
  String tr(BuildContext context) => AppLocalizations.of(context).translate(this);
}
